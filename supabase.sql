-- Jalankan sekali dalam Supabase SQL Editor.
-- Stok awal bagi 30 produk x 2 jenis balang bermula pada 0.

create table if not exists public.orinice_stock (
  id bigint generated by default as identity primary key,
  product_name text not null,
  packaging_type text not null check (packaging_type in ('BALANG 7000','BALANG 9503')),
  quantity integer not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now(),
  unique(product_name, packaging_type)
);

create table if not exists public.orinice_stock_movements (
  id uuid primary key default gen_random_uuid(),
  product_name text not null,
  packaging_type text not null check (packaging_type in ('BALANG 7000','BALANG 9503')),
  movement_type text not null check (movement_type in ('MASUK','KELUAR')),
  quantity integer not null check (quantity > 0),
  staff_name text not null,
  purpose text,
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists orinice_movements_created_at_idx
  on public.orinice_stock_movements(created_at desc);

