-- Atomic transaction: semak baki dan kemas kini stok bersama-sama.
create or replace function public.orinice_record_stock_movement(
  p_product_name text,
  p_packaging_type text,
  p_movement_type text,
  p_quantity integer,
  p_staff_name text,
  p_purpose text default null,
  p_notes text default null
) returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_delta integer;
  v_new_quantity integer;
begin
  if p_movement_type not in ('MASUK','KELUAR') then
    raise exception 'Jenis transaksi tidak sah';
  end if;
  if p_quantity is null or p_quantity <= 0 then
    raise exception 'Kuantiti mesti lebih daripada 0';
  end if;
  if p_staff_name is null or length(trim(p_staff_name)) = 0 then
    raise exception 'Nama staff wajib diisi';
  end if;

  v_delta := case when p_movement_type = 'MASUK' then p_quantity else -p_quantity end;

  update public.orinice_stock
     set quantity = quantity + v_delta, updated_at = now()
   where product_name = p_product_name
     and packaging_type = p_packaging_type
     and quantity + v_delta >= 0
  returning quantity into v_new_quantity;

  if not found then
    if exists (select 1 from public.orinice_stock
      where product_name = p_product_name and packaging_type = p_packaging_type) then
      raise exception 'Stok tidak mencukupi untuk transaksi keluar';
    else
      raise exception 'Produk atau kategori balang tidak ditemui';
    end if;
  end if;

  insert into public.orinice_stock_movements
    (product_name, packaging_type, movement_type, quantity, staff_name, purpose, notes)
  values
    (p_product_name, p_packaging_type, p_movement_type, p_quantity,
     trim(p_staff_name), nullif(trim(p_purpose),''), nullif(trim(p_notes),''));
end;
$$;

-- Untuk ujian awal sahaja. Polisi ini membenarkan akses anon dan bukan sesuai untuk produksi.
-- Sebelum digunakan staff sebenar, konfigurasi Supabase Auth dan polisi RLS mengikut peranan.
alter table public.orinice_stock enable row level security;
alter table public.orinice_stock_movements enable row level security;

-- Polisi demo untuk aplikasi dalaman: benarkan role anon/authenticated membaca.
-- Jangan aktifkan polisi write terus pada jadual; transaksi dibuat melalui fungsi RPC.
create policy "orinice stock read" on public.orinice_stock
  for select to anon, authenticated using (true);
create policy "orinice movements read" on public.orinice_stock_movements
  for select to anon, authenticated using (true);

grant select on public.orinice_stock, public.orinice_stock_movements to anon, authenticated;
grant execute on function public.orinice_record_stock_movement(text,text,text,integer,text,text,text) to anon, authenticated;